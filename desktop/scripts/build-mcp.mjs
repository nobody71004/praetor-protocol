import { build } from 'esbuild';
import { mkdirSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const out = resolve(root, 'mcp-dist');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const entries = ['server.mjs', 'agent-pipeline.mjs', 'llm-agent.mjs'];
for (const entry of entries) {
  await build({
    entryPoints: [resolve(root, 'mcp', entry)],
    outfile: resolve(out, entry),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    sourcemap: false,
    minify: false,
    legalComments: 'none',
    banner: {
      js: "// PRAETOR Command MCP runtime — generated by scripts/build-mcp.mjs\nimport { createRequire as __praetorCreateRequire } from 'node:module';\nconst require = __praetorCreateRequire(import.meta.url);",
    },
  });
  console.log(`bundled mcp/${entry} -> mcp-dist/${entry}`);
}
